package com.swizima.usersapi.entity;

import com.swizima.usersapi.entity.enums.ActivationStatus;
import com.swizima.usersapi.entity.enums.OtpChannel;
import com.swizima.usersapi.entity.enums.UserRole;
import com.swizima.usersapi.entity.enums.UsernameType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Table;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;
import lombok.experimental.SuperBuilder;
import org.hibernate.annotations.ColumnDefault;

import java.time.LocalDateTime;

/**
 * A user who can log in to the Swizima platform.
 * <p>
 * The {@code username} is either an email address or a phone number. It is always stored in a
 * normalised form (lower-cased email, or E.164 phone such as {@code +256700123456}) so that
 * uniqueness checks and logins work regardless of how the user typed it.
 */
@Entity
@Table(name = "system_users")
@Getter
@Setter
@NoArgsConstructor
@SuperBuilder
@ToString(exclude = "password")
public class SystemUser extends ParentEntity {

    @Column(name = "username", nullable = false, unique = true, length = 150)
    private String username;

    @Enumerated(EnumType.STRING)
    @Column(name = "username_type", nullable = false, length = 10)
    private UsernameType usernameType;

    /** Contact email used for EMAIL OTPs. Defaults to the username when the username is an email. */
    @Column(name = "email", length = 150)
    private String email;

    /** Contact phone (E.164) used for SMS and WhatsApp OTPs. Defaults to the username when it is a phone. */
    @Column(name = "phone_number", length = 20)
    private String phoneNumber;

    /** Channel used for OTPs when the login request does not specify one. */
    @Builder.Default
    @Enumerated(EnumType.STRING)
    @Column(name = "preferred_otp_channel", nullable = false, length = 20)
    private OtpChannel preferredOtpChannel = OtpChannel.EMAIL;

    /** BCrypt hash - never the raw password. */
    @Column(name = "password", nullable = false)
    private String password;

    @Builder.Default
    @Column(name = "enabled", nullable = false)
    private boolean enabled = true;

    @Builder.Default
    @Enumerated(EnumType.STRING)
    @Column(name = "activation_status", nullable = false, length = 30)
    private ActivationStatus activationStatus = ActivationStatus.PENDING_ACTIVATION;

    @Builder.Default
    @Enumerated(EnumType.STRING)
    @ColumnDefault("'USER'")
    @Column(name = "role", nullable = false, length = 30)
    private UserRole role = UserRole.USER;

    /** True when the current password was generated by the system; user must change it on next login. */
    @Builder.Default
    @Column(name = "password_system_generated", nullable = false)
    private boolean passwordSystemGenerated = false;

    @Column(name = "password_changed_at")
    private LocalDateTime passwordChangedAt;

    @Column(name = "last_login_at")
    private LocalDateTime lastLoginAt;
}
